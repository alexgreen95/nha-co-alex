CREATE FUNCTION public.nca_skip_admin_comment_mention() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $capture$
BEGIN
 IF NEW.type='mention' AND EXISTS (
  SELECT 1 FROM public.notifications n WHERE n.type='comment'
  AND n.user_id=NEW.user_id AND n.actor_id=NEW.actor_id AND n.comment_id=NEW.comment_id
 ) THEN RETURN NULL; END IF;
 RETURN NEW;
END;
$capture$;
REVOKE ALL ON FUNCTION public.nca_skip_admin_comment_mention() FROM PUBLIC;
CREATE FUNCTION public.nca_notify_comment_unlike() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $capture$
DECLARE recipient uuid;
BEGIN
 SELECT user_id INTO recipient FROM public.comments WHERE id=OLD.comment_id;
 IF NOT FOUND THEN RETURN OLD; END IF;
 PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(
  recipient::text || ':' || OLD.user_id::text || ':' || OLD.comment_id::text || ':comment_like',0));
 DELETE FROM public.notifications WHERE actor_id=OLD.user_id AND comment_id=OLD.comment_id
  AND user_id=recipient AND type='comment_like';
 RETURN OLD;
END;
$capture$;
REVOKE ALL ON FUNCTION public.nca_notify_comment_unlike() FROM PUBLIC;
CREATE TRIGGER nca_admin_comment_mention_dedupe BEFORE INSERT ON public.notifications FOR EACH ROW EXECUTE FUNCTION public.nca_skip_admin_comment_mention();
CREATE TRIGGER nca_comment_unlike_notification AFTER DELETE ON public.comment_likes FOR EACH ROW EXECUTE FUNCTION public.nca_notify_comment_unlike();

